
def area(a):
    """
    Возвращает площадь квадрата.
    Параметры:
        a(float)-сторона квадрата.
    Пример:
        area(2)=2 * 2 = 4
    """
    return a * a


def perimeter(a):
    """
    Возвращает периметр квадрата.
    Параметры:
        a(float)-сторона квадрата.
    Пример:
        perimeter(2)=2 * 4 = 8
    """
    return 4 * a
