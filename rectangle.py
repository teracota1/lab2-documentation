def area(a, b):
    """
    Возвращает площадь прямоугольника.
    Параметры:
        a(float)-сторона прямоугольника.
        b(float)-другая сторона прямоугольника.
    Пример:
        area(2,3)=2 * 3 = 6
    """
    return a * b

def perimeter(a, b):
    """
    Возвращает периметр прямоугольника.
    Параметры:
        a(float)-сторона прямоугольника.
        b(float)-другая сторона прямоугольника.
    Пример:
        perimeter(2,3)=2*2 + 2*3 = 10
    """
    return 2*a + 2*b
